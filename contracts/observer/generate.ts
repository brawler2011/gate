import {rm, mkdir} from 'node:fs/promises';

import {GoGenerator, GO_COMMON_PRESET, TypeScriptGenerator} from '@asyncapi/modelina';
import {Parser} from '@asyncapi/parser';

const source = await Bun.file('contracts/observer/v1/asyncapi.yaml').text();
const {document, diagnostics} = await new Parser().parse(source);
const errors = diagnostics.filter(diagnostic => diagnostic.severity === 0);
if (!document || errors.length) {
  throw new Error(JSON.stringify(errors, null, 2));
}
if (process.argv.includes('--validate')) {
  process.exit(0);
}

// Preserve absent values separately from zero/false, and use the domain's Go formats.
const scalar = (type: string, args: {partOfProperty?: {required: boolean}; constrainedModel: {options: {isNullable?: boolean}}}): string =>
  (args.partOfProperty && !args.partOfProperty.required) || args.constrainedModel.options.isNullable ? `*${type}` : type;

const go = new GoGenerator({
  presets: [{preset: GO_COMMON_PRESET, options: {addJsonTag: true}}],
  typeMapping: {
    Integer: args => scalar(args.constrainedModel.originalInput.format === 'int32' ? 'int32' : 'int64', args),
    Boolean: args => scalar('bool', args),
    String: args => {
      switch (args.constrainedModel.originalInput.format) {
        case 'uuid':
          args.dependencyManager.addDependency('github.com/google/uuid');
          return scalar('uuid.UUID', args);
        case 'date-time':
          args.dependencyManager.addDependency('time');
          return scalar('time.Time', args);
        default:
          return scalar('string', args);
      }
    },
  },
});
const ts = new TypeScriptGenerator({modelType: 'interface', rawPropertyNames: true});
const schemas = (Bun.YAML.parse(source) as {components: {schemas: Record<string, object>}}).components.schemas;

for (const [generator, directory, extension, options, closeSchemas] of [
  [go, 'backend/contracts/observer/v1', 'go', {packageName: 'observerv1'}, ['SubmissionsWsCloseCode', 'SubmissionsWsCloseReason']],
  [ts, 'frontend/contracts/observer/v1', 'ts', {}, []],
] as const) {
  const models = await generator.generateCompleteModels(document, options);
  // Close frames are protocol metadata, rather than application message payloads.
  for (const name of closeSchemas) {
    models.push(...await generator.generateCompleteModels(schemas[name], options));
  }
  await rm(directory, {recursive: true, force: true});
  await mkdir(directory, {recursive: true});
  for (const model of models) {
    await Bun.write(`${directory}/${model.modelName}.${extension}`,
      `// Code generated by Modelina. DO NOT EDIT.\n${model.result}`);
  }
}
