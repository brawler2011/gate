// Package spec describes author packages independently of their eventual draft layout.
package spec

import (
	"fmt"
	"io"
	"io/fs"
	"strings"

	"github.com/brawler2011/gate/backend/pkg/points"
)

// Paths are slash-separated relative to the package root; names may repeat.
type Problem struct {
	Title         string
	Type          string // "pass-fail", "scoring" or "interactive"
	TimeLimitMs   int
	MemoryLimitMb int
	Checker       *Program
	Validator     *Program
	Interactor    *Program
	// Tests identify generators by path.
	Generators []Program
	Solutions  []Program
	// Identifies a solution by path; empty means none.
	MainSolution string
	Library      []File
	Statements   []Statement
	Assets       []File
	Groups       []Group
	// Text test line endings are normalized from CRLF to LF during import.
	TextTests bool
}

type File struct {
	Name string
	Path string
	// Gate supplies system library contents; Path still identifies the dependency.
	System bool
	// Pinned keeps the file's text even when it is an upstream copy of a system file.
	Pinned bool
}

type Program struct {
	File
	// An absent language lets the file extension suggest a configuration.
	Language string
	// Dependencies maps include names to library paths; nil exposes the whole library by file name.
	Dependencies map[string]string
	// Standard checker sources remain in the package even when identified by testlib name.
	Standard string
}

// Statements contain either one LaTeX file or Markdown files per section.
type Statement struct {
	Language string
	TeX      string
	Sections map[string]string
}

type Group struct {
	Name      string
	Policy    string // "complete" or "each"
	DependsOn []string
	Tests     []Test
}

// An empty Answer is generated by AnswerSolution, or by the main solution when that is empty too.
type Test struct {
	Input          string
	Generator      string
	Args           []string
	Answer         string
	AnswerSolution string
	Points         points.Value
	Sample         bool
	// Positive ordinals order tests across groups; zero keeps the group order.
	Ordinal int
}

// Metadata reads have a separate bound from the draft quotas enforced during content import.
const MaxMetadataBytes = 4 << 20

func ReadFile(fsys fs.FS, name string) ([]byte, error) {
	f, err := fsys.Open(name)
	if err != nil {
		return nil, fmt.Errorf("open %s: %w", name, err)
	}
	defer f.Close()
	data, err := io.ReadAll(io.LimitReader(f, MaxMetadataBytes+1))
	if err != nil {
		return nil, fmt.Errorf("read %s: %w", name, err)
	}
	if len(data) > MaxMetadataBytes {
		return nil, fmt.Errorf("%s is larger than %d bytes", name, MaxMetadataBytes)
	}
	return data, nil
}

// Interactive inputs are private interactor data and must not become public samples.
func (p *Problem) KeepInteractiveInputsPrivate() {
	if p.Type != "interactive" {
		return
	}
	for i := range p.Groups {
		for j := range p.Groups[i].Tests {
			p.Groups[i].Tests[j].Sample = false
		}
	}
}

// Generators run as argv, never through a shell; only quoting and escaping are supported.
// Polygon/gfmt output redirection (> $) is stripped; other shell syntax is rejected.
func ParseCommand(command string) ([]string, error) {
	command = strings.TrimSpace(command)
	command = strings.TrimSpace(strings.TrimSuffix(command, "> $"))
	args := []string{}
	var current strings.Builder
	var quote rune
	escaped, started := false, false
	for _, r := range command {
		switch {
		case escaped:
			current.WriteRune(r)
			escaped = false
		case r == '\\' && quote != '\'':
			escaped = true
		case quote != 0:
			if r == quote {
				quote = 0
			} else {
				current.WriteRune(r)
			}
		case r == '\'' || r == '"':
			quote = r
		case r == ' ' || r == '\t':
			if started {
				args = append(args, current.String())
				current.Reset()
				started = false
			}
			continue
		case strings.ContainsRune("|;&><`$\n\r", r):
			return nil, fmt.Errorf("shell syntax is not supported in generator command %q", command)
		default:
			current.WriteRune(r)
		}
		started = true
	}
	if quote != 0 || escaped {
		return nil, fmt.Errorf("unterminated argument in generator command %q", command)
	}
	if started {
		args = append(args, current.String())
	}
	if len(args) == 0 {
		return nil, fmt.Errorf("empty generator command")
	}
	return args, nil
}

// FormatCommand quotes argv so that ParseCommand returns it unchanged.
func FormatCommand(argv []string) string {
	quoted := make([]string, len(argv))
	for i, arg := range argv {
		if arg != "" && !strings.ContainsFunc(arg, func(r rune) bool { return !isPlain(r) }) {
			quoted[i] = arg
		} else {
			quoted[i] = "'" + strings.ReplaceAll(arg, "'", `'\''`) + "'"
		}
	}
	return strings.Join(quoted, " ")
}

func isPlain(r rune) bool {
	return r >= 'a' && r <= 'z' || r >= 'A' && r <= 'Z' || r >= '0' && r <= '9' || strings.ContainsRune("-_.,:=+/@%", r)
}

func IsSourceFile(path string) bool {
	switch strings.ToLower(extension(path)) {
	case ".cpp", ".cc", ".cxx", ".c", ".py", ".go", ".java", ".kt", ".pas", ".dpr", ".rs", ".cs", ".js":
		return true
	}
	return false
}

func IsHeaderFile(path string) bool {
	switch strings.ToLower(extension(path)) {
	case ".h", ".hpp", ".hh", ".hxx":
		return true
	}
	return false
}

func Stem(path string) string {
	base := path[strings.LastIndex(path, "/")+1:]
	return strings.TrimSuffix(base, extension(base))
}

func extension(path string) string {
	base := path[strings.LastIndex(path, "/")+1:]
	if i := strings.LastIndex(base, "."); i > 0 {
		return base[i:]
	}
	return ""
}
